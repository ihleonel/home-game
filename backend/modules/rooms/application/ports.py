from typing import Protocol


class GhostReaping(Protocol):
    def reap(self, *, room_id: int | None = None): ...


class VoteCancellation(Protocol):
    def session_was_removed(self, room_id: int, participant_id: int) -> bool: ...

    def target_reconnected(self, room_id: int, participant_id: int): ...

    def participant_disconnected(self, room_id: int, participant_id: int): ...

    def participant_left(self, room_id: int, participant_id: int): ...
