/**
 * The black silhouette printed on each flat token (S3 of
 * ``monopoly-flat-figures.md``).
 *
 * The scene used to build every classic piece out of primitives -- a cylinder for
 * the hat's crown, cones for the cat's ears -- and at a seat's distance those
 * assemblies read as lumps. What the owner of the look asked for is the printed
 * set itself: **flat silhouettes**, side by side, like the sheet they sent. This
 * module is that sheet as data.
 *
 * **No binary asset**, because S3 of ``monopoly-3d-table.md`` still rules: the
 * shapes are paths, and ``figureTexture.ts`` paints them on a canvas when the
 * scene mounts, exactly like the forty cells and the wood. Eight of them were
 * traced once from the supplied sheet (783x511 px) with a marching-squares pass
 * and simplified; the two markers that sheet does not carry -- the iron and the
 * boot -- and the neutral counter were drawn here in the same weight.
 *
 * A figure is a list of closed loops in a **0..100 box, ``y`` pointing down**,
 * the canvas' own space, and every loop of a figure is filled **even-odd**: a
 * point is ink when an odd number of loops enclose it. So the outline is ink, a
 * loop inside it is a white detail (the penguin's belly, the car's windows, the
 * ring of the iron's handle), and a loop inside *that* is ink again (the hub of
 * the car's wheel). Loops nest; what even-odd needs is that no two boundaries
 * cross, which is true of every figure here.
 *
 * Pure and free of ``three``: the catalogue is pinned by the DOM-less harness,
 * and the painter is the only half that needs a document.
 */

